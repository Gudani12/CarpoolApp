CREATE TABLE IF NOT EXISTS public.driver_ratings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  ride_id TEXT NOT NULL,
  driver_id BIGINT NOT NULL,
  passenger_clerk_id TEXT NOT NULL,
  rating SMALLINT NOT NULL,
  comment TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT driver_ratings_pkey PRIMARY KEY (id),
  CONSTRAINT driver_ratings_ride_id_key UNIQUE (ride_id),
  CONSTRAINT driver_ratings_comment_check
    CHECK (comment IS NULL OR char_length(comment) <= 500),
  CONSTRAINT driver_ratings_rating_check CHECK (rating BETWEEN 1 AND 5)
);

