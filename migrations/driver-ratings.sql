DROP FUNCTION IF EXISTS public.record_driver_rating(BIGINT, TEXT, BIGINT, INTEGER, TEXT);

CREATE OR REPLACE FUNCTION public.record_driver_rating(
  p_ride_id TEXT,
  p_passenger_clerk_id TEXT,
  p_driver_id BIGINT,
  p_rating INTEGER,
  p_comment TEXT
)
RETURNS TABLE (average_rating NUMERIC, rating_count INTEGER)
LANGUAGE PLPGSQL
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_average_rating NUMERIC;
  v_rating_count INTEGER;
BEGIN
  PERFORM 1
  FROM public.drivers
  WHERE id = p_driver_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Driver not found';
  END IF;

  INSERT INTO public.driver_ratings (
    ride_id,
    driver_id,
    passenger_clerk_id,
    rating,
    comment
  )
  VALUES (
    p_ride_id,
    p_driver_id,
    p_passenger_clerk_id,
    p_rating,
    p_comment
  );

  SELECT ROUND(AVG(driver_rating.rating)::NUMERIC, 1), COUNT(*)::INTEGER
  INTO v_average_rating, v_rating_count
  FROM public.driver_ratings AS driver_rating
  WHERE driver_rating.driver_id = p_driver_id;

  UPDATE public.drivers
  SET rating = v_average_rating,
      rating_count = v_rating_count
  WHERE id = p_driver_id;

  RETURN QUERY SELECT v_average_rating, v_rating_count;
END;
$$;

REVOKE ALL ON FUNCTION public.record_driver_rating(TEXT, TEXT, BIGINT, INTEGER, TEXT)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_driver_rating(TEXT, TEXT, BIGINT, INTEGER, TEXT)
  TO service_role;
